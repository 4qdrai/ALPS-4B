"""
Two Rooms Dataset for ALPS-4B Benchmark.

Loads pre-generated .pt episode data and serves sliding-window clips of
consecutive frames for spatiotemporal predictive learning.

Expected .pt file format (from data_generator):
{
    'frames':         Tensor [total_frames, 3, 128, 128]  float32 (RGB, [0,1])
    'actions':        Tensor [total_frames]               int64   (0=up, 1=down, 2=left, 3=right)
    'positions':      Tensor [total_frames, 2]            float32 (x, y continuous coords)
    'room_ids':       Tensor [total_frames]               int64   (0=left room, 1=right room)
    'episode_starts': Tensor [num_episodes]               int64   (frame index where each episode begins)
}
"""

import torch
import torch.nn.functional as F
from torch.utils.data import Dataset
from pathlib import Path
from typing import Optional


class TwoRoomsDataset(Dataset):
    """
    PyTorch Dataset for the Two Rooms navigation benchmark.

    Extracts all valid sliding-window clips of `clip_length` consecutive frames
    within each episode, using a configurable stride to control overlap.

    Each sample is a dict with:
        - 'video_frames':  [3, T, 128, 128]  float32, CHW format for ViT
        - 'actions':       [T]               int64,   discrete action indices
        - 'actions_onehot':[T, 4]            float32, one-hot encoded actions
        - 'positions':     [T, 2]            float32, agent (x, y) coordinates
        - 'room_ids':      [T]              int64,   which room the agent is in
    """

    NUM_ACTIONS = 4  # up=0, down=1, left=2, right=3

    def __init__(
        self,
        data_path: str,
        clip_length: int = 8,
        stride: int = 4,
        transform: Optional[callable] = None,
    ):
        """
        Args:
            data_path:    Path to the .pt file generated by data_generator.
            clip_length:  Number of consecutive frames per clip (default: 8).
            stride:       Step size between clip start indices (default: 4).
                          Stride < clip_length creates overlapping clips.
            transform:    Optional callable applied to video_frames tensor.
        """
        super().__init__()
        self.clip_length = clip_length
        self.stride = stride
        self.transform = transform

        # --- Load the pre-generated data ---
        data_path = Path(data_path)
        if not data_path.exists():
            raise FileNotFoundError(
                f"Two Rooms data file not found: {data_path}\n"
                f"Generate it first with the data_generator module."
            )

        print(f"[TwoRoomsDataset] Loading data from {data_path} ...")
        data = torch.load(str(data_path), map_location="cpu", weights_only=True)

        self.frames: torch.Tensor = data.get("frames", data.get("observations"))
        if self.frames is None:
            raise KeyError("The loaded dataset must contain either 'frames' or 'observations'.")
        self.actions: torch.Tensor = data["actions"]          # [total_frames]
        self.positions: torch.Tensor = data["positions"]      # [total_frames, 2]
        self.room_ids: torch.Tensor = data["room_ids"]        # [total_frames]
        
        episode_starts_raw = data["episode_starts"]
        if isinstance(episode_starts_raw, list):
            self.episode_starts = torch.tensor(episode_starts_raw, dtype=torch.long)
        else:
            self.episode_starts: torch.Tensor = episode_starts_raw

        total_frames = self.frames.shape[0]
        num_episodes = self.episode_starts.shape[0]
        print(
            f"[TwoRoomsDataset] Loaded {total_frames} frames across "
            f"{num_episodes} episodes."
        )

        # --- Pre-compute all valid clip indices ---
        # A clip is valid if all clip_length frames belong to the same episode.
        # We compute episode boundaries (start, end) and enumerate windows.
        self.clip_indices = self._build_clip_indices(total_frames)
        print(
            f"[TwoRoomsDataset] Extracted {len(self.clip_indices)} clips "
            f"(clip_length={clip_length}, stride={stride})."
        )

    def _build_clip_indices(self, total_frames: int) -> list:
        """
        Enumerate all valid (start_frame) indices for sliding-window clips,
        ensuring no clip crosses an episode boundary.

        Returns:
            List of integer start-frame indices.
        """
        episode_starts = self.episode_starts.tolist()
        num_episodes = len(episode_starts)
        clip_starts = []

        for ep_idx in range(num_episodes):
            ep_start = episode_starts[ep_idx]

            # Determine episode end (exclusive)
            if ep_idx + 1 < num_episodes:
                ep_end = episode_starts[ep_idx + 1]
            else:
                ep_end = total_frames

            ep_length = ep_end - ep_start

            # Skip episodes shorter than one clip
            if ep_length < self.clip_length:
                continue

            # Enumerate windows with the given stride within this episode
            max_clip_start = ep_end - self.clip_length
            frame_idx = ep_start
            while frame_idx <= max_clip_start:
                clip_starts.append(frame_idx)
                frame_idx += self.stride

        return clip_starts

    def __len__(self) -> int:
        return len(self.clip_indices)

    def __getitem__(self, idx: int) -> dict:
        """
        Returns a single clip as a dictionary of tensors.

        Returns:
            dict with keys:
                'video_frames':   [3, T, 128, 128] float32  (CHW for ViT)
                'actions':        [T]               int64
                'actions_onehot': [T, 4]            float32
                'positions':      [T, 2]            float32
                'room_ids':       [T]               int64
        """
        start = self.clip_indices[idx]
        end = start + self.clip_length

        # Extract the clip slice
        # frames stored as [total, C, H, W] → clip is [T, C, H, W]
        video_clip = self.frames[start:end]   # [T, 3, 128, 128]
        actions = self.actions[start:end]      # [T]
        positions = self.positions[start:end]  # [T, 2]
        room_ids = self.room_ids[start:end]    # [T]

        # Reshape video to CHW temporal format: [C, T, H, W] for the 3D ViT
        video_frames = video_clip.permute(1, 0, 2, 3).contiguous()  # [3, T, 128, 128]

        # Ensure float32 and normalized to [0, 1]
        video_frames = video_frames.float()
        if video_frames.max() > 1.0:
            video_frames = video_frames / 255.0

        # One-hot encode actions: [T] int64 → [T, 4] float32
        actions_onehot = F.one_hot(
            actions.long(), num_classes=self.NUM_ACTIONS
        ).float()  # [T, 4]

        # Optional user transform (augmentation, normalization, etc.)
        if self.transform is not None:
            video_frames = self.transform(video_frames)

        return {
            "video_frames": video_frames,       # [3, T, 128, 128]
            "actions": actions.long(),           # [T]
            "actions_onehot": actions_onehot,    # [T, 4]
            "positions": positions.float(),      # [T, 2]
            "room_ids": room_ids.long(),         # [T]
        }

    def get_episode_count(self) -> int:
        """Returns the number of episodes in the dataset."""
        return self.episode_starts.shape[0]

    def get_stats(self) -> dict:
        """Returns basic statistics about the loaded dataset."""
        total_frames = self.frames.shape[0]
        action_counts = torch.bincount(self.actions.long(), minlength=self.NUM_ACTIONS)
        room_counts = torch.bincount(self.room_ids.long(), minlength=2)

        return {
            "total_frames": total_frames,
            "num_episodes": self.get_episode_count(),
            "num_clips": len(self),
            "clip_length": self.clip_length,
            "stride": self.stride,
            "resolution": (self.frames.shape[2], self.frames.shape[3]),
            "action_distribution": {
                "up": action_counts[0].item(),
                "down": action_counts[1].item(),
                "left": action_counts[2].item(),
                "right": action_counts[3].item(),
            },
            "room_distribution": {
                "left_room": room_counts[0].item(),
                "right_room": room_counts[1].item(),
            },
            "position_range_x": (
                self.positions[:, 0].min().item(),
                self.positions[:, 0].max().item(),
            ),
            "position_range_y": (
                self.positions[:, 1].min().item(),
                self.positions[:, 1].max().item(),
            ),
        }


def _test_dataset():
    """Quick smoke test: create a tiny synthetic .pt file and load it."""
    import tempfile, os

    num_frames = 100
    num_episodes = 3
    ep_starts = torch.tensor([0, 35, 70], dtype=torch.long)

    data = {
        "frames": torch.rand(num_frames, 3, 128, 128),
        "actions": torch.randint(0, 4, (num_frames,)),
        "positions": torch.rand(num_frames, 2) * 10.0,
        "room_ids": torch.randint(0, 2, (num_frames,)),
        "episode_starts": ep_starts,
    }

    with tempfile.NamedTemporaryFile(suffix=".pt", delete=False) as f:
        torch.save(data, f.name)
        tmp_path = f.name

    try:
        ds = TwoRoomsDataset(tmp_path, clip_length=8, stride=4)
        print(f"\nDataset length: {len(ds)}")
        print(f"Stats: {ds.get_stats()}")

        sample = ds[0]
        for k, v in sample.items():
            print(f"  {k}: shape={v.shape}, dtype={v.dtype}")

        # Verify shapes
        assert sample["video_frames"].shape == (3, 8, 128, 128)
        assert sample["actions"].shape == (8,)
        assert sample["actions_onehot"].shape == (8, 4)
        assert sample["positions"].shape == (8, 2)
        assert sample["room_ids"].shape == (8,)
        assert sample["video_frames"].min() >= 0.0
        assert sample["video_frames"].max() <= 1.0
        assert sample["actions_onehot"].sum(dim=-1).allclose(torch.ones(8))

        print("\n✓ All TwoRoomsDataset assertions passed!")
    finally:
        os.unlink(tmp_path)


if __name__ == "__main__":
    _test_dataset()
